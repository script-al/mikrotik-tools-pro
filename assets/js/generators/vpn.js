/**
 * Generate L2TP/IPSec server setup.
 * @param {Object} cfg
 * @returns {string}
 */
function generateL2TP(cfg) {
  const defaults = {
    server_ip_pool:   '192.168.200.0/24',
    pool_range:       '192.168.200.100-192.168.200.200',
    pool_name:        'l2tp-pool',
    ipsec_secret:     'MyIPSecSecret123!',
    profile_name:     'l2tp-profile',
    local_address:    '192.168.200.1',
    dns:              '8.8.8.8,8.8.4.4',
    clients: [
      { username: 'vpnuser1', password: 'Pass1234!', ip: '192.168.200.101' },
    ],
    wan_interface:    'ether1',
    comment:          'Generated by ComitTools Pro - L2TP/IPSec',
  };

  const c = Object.assign({}, defaults, cfg);

  const lines = [
    `#####################################################################`,
    `# L2TP/IPSec VPN Server`,
    `#####################################################################`,
    ``,
    `# Step 1: IP Pool`,
    `/ip pool`,
    `add name=${c.pool_name} ranges=${c.pool_range} \\`,
    `    comment="${c.comment}"`,
    ``,
    `# Step 2: PPP Profile`,
    `/ppp profile`,
    `add name=${c.profile_name} \\`,
    `    local-address=${c.local_address} \\`,
    `    remote-address=${c.pool_name} \\`,
    `    dns-server=${c.dns} \\`,
    `    use-encryption=yes \\`,
    `    comment="${c.comment}"`,
    ``,
    `# Step 3: Enable L2TP Server`,
    `/interface l2tp-server server`,
    `set enabled=yes \\`,
    `    use-ipsec=required \\`,
    `    ipsec-secret=${c.ipsec_secret} \\`,
    `    default-profile=${c.profile_name} \\`,
    `    authentication=mschap2`,
    ``,
    `# Step 4: PPP Secrets (users)`,
    `/ppp secret`,
  ];

  c.clients.forEach(client => {
    const ipLine = client.ip ? ` remote-address=${client.ip}` : '';
    lines.push(
      `add name=${client.username} password="${client.password}" \\`,
      `    service=l2tp profile=${c.profile_name}${ipLine} \\`,
      `    comment="${c.comment}"`,
    );
  });

  lines.push(
    ``,
    `# Step 5: Firewall rules for L2TP/IPSec`,
    `/ip firewall filter`,
    `add action=accept chain=input protocol=udp dst-port=500,4500 \\`,
    `    comment="L2TP/IPSec: IKE + NAT-T"`,
    `add action=accept chain=input protocol=udp dst-port=1701 \\`,
    `    comment="L2TP: UDP 1701"`,
    `add action=accept chain=input protocol=ipsec-ah \\`,
    `    comment="IPSec AH"`,
    `add action=accept chain=input protocol=ipsec-esp \\`,
    `    comment="IPSec ESP"`,
    ``,
  );

  return lines.join('\n');
}


/**
 * Generate VPN script based on type.
 *
 * @param {string} type   - 'wireguard' | 'l2tp' | 'pptp' | 'sstp'
 * @param {Object} config - VPN-specific configuration
 *
 * WireGuard config keys:
 *   interface_name, listen_port, server_ip, server_pub_ip, clients[], dns
 *
 * L2TP config keys:
 *   pool_range, pool_name, ipsec_secret, profile_name, local_address, dns, clients[]
 *
 * PPTP config keys:
 *   pool_range, pool_name, local_address, profile_name, dns, clients[]
 *
 * SSTP config keys:
 *   pool_range, pool_name, local_address, profile_name, dns, certificate, clients[]
 *
 * clients[] always: [{ username, password, ip? }]
 * For WireGuard clients: [{ name, ip, pubkey }]
 *
 * @returns {string} RouterOS script
 */
function generateVPN(type, config) {
  const t = String(type).toLowerCase().trim();
  const toolId = 'vpn-' + t;
  if (typeof Auth !== 'undefined' && Auth.canAccessTool) {
    const access = Auth.canAccessTool(toolId);
    if (!access.allowed) {
      return '# ================================================================\n# COMITTOOLS PRO — ACCESS RESTRICTED (SUBSCRIPTION REQUIRED)\n# ' + (access.message || 'Fitur ini memerlukan paket langganan aktif.') + '\n# Silakan SUBSCRIBE untuk membuka fitur VPN.\n# ================================================================';
    }
  }

  switch (t) {
    case 'wireguard': return generateWireGuard(config || {});
    case 'l2tp':      return generateL2TP(config || {});
    case 'pptp':      return generatePPTP(config || {});
    case 'sstp':      return generateSSTP(config || {});
    default:
      throw new Error(`Unknown VPN type: "${type}". Use: wireguard, l2tp, pptp, sstp`);
  }
}


/**
 * Generate WireGuard server + client config.
 * @param {Object} cfg
 * @returns {string}
 */
function generateWireGuard(cfg) {
  const defaults = {
    interface_name:  'wg0',
    listen_port:     13231,
    server_ip:       '10.10.0.1/24',
    server_pub_ip:   '203.0.113.1',  // Router's public IP
    clients: [
      { name: 'client1', ip: '10.10.0.2/32', pubkey: '<CLIENT1_PUBLIC_KEY>' },
    ],
    dns:             '1.1.1.1',
    comment:         'Generated by ComitTools Pro - WireGuard',
  };

  const c = Object.assign({}, defaults, cfg);
  const serverIP = c.server_ip.split('/')[0];

  const lines = [
    `#####################################################################`,
    `# WireGuard VPN Server - RouterOS v7 Only`,
    `#####################################################################`,
    ``,
    `# Step 1: Create WireGuard interface`,
    `/interface wireguard`,
    `add name=${c.interface_name} listen-port=${c.listen_port} \\`,
    `    comment="${c.comment}"`,
    ``,
    `# Step 2: Assign IP to WireGuard interface`,
    `/ip address`,
    `add address=${c.server_ip} interface=${c.interface_name} \\`,
    `    comment="${c.comment}"`,
    ``,
    `# Step 3: Add WireGuard peers (clients)`,
    `/interface wireguard peers`,
  ];

  c.clients.forEach((client, i) => {
    const clientIP = client.ip.split('/')[0];
    lines.push(
      `add interface=${c.interface_name} \\`,
      `    public-key="${client.pubkey}" \\`,
      `    allowed-address=${client.ip} \\`,
      `    comment="WireGuard Peer: ${client.name}"`,
    );
  });

  lines.push(
    ``,
    `# Step 4: Firewall - allow WireGuard port`,
    `/ip firewall filter`,
    `add action=accept chain=input protocol=udp dst-port=${c.listen_port} \\`,
    `    comment="Allow WireGuard UDP"`,
    ``,
    `# Step 5: Route VPN clients to LAN (if needed)`,
    `/ip route`,
    `add dst-address=10.10.0.0/24 gateway=${c.interface_name} \\`,
    `    comment="WireGuard VPN subnet"`,
    ``,
    `#####################################################################`,
    `# WireGuard CLIENT Config (generate on client device):`,
    `# [Interface]`,
    `# PrivateKey = <CLIENT_PRIVATE_KEY>`,
    `# Address    = 10.10.0.X/24`,
    `# DNS        = ${c.dns}`,
    `#`,
    `# [Peer]`,
    `# PublicKey           = <SERVER_PUBLIC_KEY>  (from /interface wireguard print)`,
    `# Endpoint            = ${c.server_pub_ip}:${c.listen_port}`,
    `# AllowedIPs          = 0.0.0.0/0`,
    `# PersistentKeepalive = 25`,
    `#####################################################################`,
    ``,
  );

  return lines.join('\n');
}


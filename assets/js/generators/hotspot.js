/**
 * Hotspot Setup Generator
 * Generates complete MikroTik RouterOS Hotspot scripts
 *
 * Supports:
 *  - CHAP, PAP, MAC-based login
 *  - IP Pool + DHCP Server configuration
 *  - Hotspot Profile with trial mode
 *  - User Profile templates (1H, 1D, 7D, 30D)
 *  - Walled Garden entries
 *  - Cookie timeout and session settings
 *
 * @module hotspot
 */

'use strict';

/**
 * Validate and normalize hotspot configuration.
 * @param {Object} config
 * @returns {Object}
 */
function validateHotspotConfig(config) {
  const defaults = {
    // Interface & IP
    hs_interface:     'bridge',
    hs_ip:            '10.5.50.1/24',      // Hotspot interface IP/mask
    hs_network:       '10.5.50.0/24',      // Hotspot network
    hs_dns_name:      'hotspot.local',     // DNS name for captive portal
    hs_gateway:       '10.5.50.1',

    // DHCP
    pool_name:        'hs-pool',
    pool_range:       '10.5.50.2-10.5.50.254',
    dhcp_lease_time:  '1h',

    // Auth
    login_method:     'chap',             // 'chap' | 'pap' | 'mac' | 'http-chap'
    cookie_lifetime:  '3d',
    session_timeout:  '0s',               // 0 = no limit

    // Hotspot profile
    profile_name:     'hsprof1',
    smtp_server:      '0.0.0.0',
    hotspot_address:  '',                 // auto from hs_ip
    html_directory:   'hotspot',
    rate_limit:       '',                 // blank = no limit on profile

    // Trial
    trial_enabled:    false,
    trial_uptime:     '30m',
    trial_limit:      '30m',             // session limit for trial
    trial_reset:      '1d',

    // User profiles
    user_profiles:    ['1H', '1D', '7D', '30D'],
    profile_speeds: {
      '1H':  { up: '2M', down: '5M' },
      '1D':  { up: '3M', down: '8M' },
      '7D':  { up: '5M', down: '10M' },
      '30D': { up: '10M', down: '20M' },
    },

    // Walled Garden
    walled_garden: [
      '*.google.com',
      '*.facebook.com',
      '*.twitter.com',
    ],

    // General
    dns_servers:   '8.8.8.8,8.8.4.4',
    comment:       'Generated by ComitTools Pro - Hotspot',
  };

  return Object.assign({}, defaults, config);
}

/**
 * Build /ip pool section.
 */
function buildPool(cfg) {
  return [
    `# ---- IP Pool ----`,
    `/ip pool`,
    `add name=${cfg.pool_name} ranges=${cfg.pool_range} \\`,
    `    comment="${cfg.comment}"`,
    ``,
  ].join('\n');
}

/**
 * Build /ip dhcp-server and /ip dhcp-server network sections.
 */
function buildDHCP(cfg) {
  const net = cfg.hs_network;
  const gw  = cfg.hs_gateway;

  return [
    `# ---- DHCP Server ----`,
    `/ip dhcp-server`,
    `add address-pool=${cfg.pool_name} disabled=no interface=${cfg.hs_interface} \\`,
    `    lease-time=${cfg.dhcp_lease_time} name=dhcp-hotspot \\`,
    `    comment="${cfg.comment}"`,
    ``,
    `/ip dhcp-server network`,
    `add address=${net} gateway=${gw} dns-server=${cfg.dns_servers} \\`,
    `    comment="${cfg.comment}"`,
    ``,
  ].join('\n');
}

/**
 * Build hotspot server and server profile.
 */
function buildHotspotProfile(cfg) {
  const addr = cfg.hotspot_address || cfg.hs_ip.split('/')[0];
  const loginMethod = cfg.login_method === 'mac' ? 'mac' : cfg.login_method;
  const trialLines  = [];

  if (cfg.trial_enabled) {
    trialLines.push(
      `    trial-uptime=${cfg.trial_uptime} \\`,
      `    trial-uptime-limit=${cfg.trial_limit} \\`,
      `    trial-reset-by=login \\`,
    );
  }

  const cookieLine   = `    http-cookie-lifetime=${cfg.cookie_lifetime} \\`;
  const sessionLine  = cfg.session_timeout !== '0s'
    ? `    session-timeout=${cfg.session_timeout} \\`
    : '';
  const rateLine     = cfg.rate_limit
    ? `    rate-limit="${cfg.rate_limit}" \\`
    : '';

  const profileLines = [
    `# ---- Hotspot Profile ----`,
    `/ip hotspot profile`,
    `add name=${cfg.profile_name} \\`,
    `    hotspot-address=${addr} \\`,
    `    dns-name=${cfg.hs_dns_name} \\`,
    `    html-directory=${cfg.html_directory} \\`,
    `    login-by=${loginMethod} \\`,
    cookieLine,
    sessionLine,
    rateLine,
    ...trialLines,
    `    smtp-server=${cfg.smtp_server} \\`,
    `    comment="${cfg.comment}"`,
    ``,
  ].filter(l => l !== '');

  return profileLines.join('\n') + '\n';
}

/**
 * Build hotspot server instance.
 */
function buildHotspotServer(cfg) {
  return [
    `# ---- Hotspot Server ----`,
    `/ip hotspot`,
    `add name=hotspot1 \\`,
    `    interface=${cfg.hs_interface} \\`,
    `    profile=${cfg.profile_name} \\`,
    `    address-pool=${cfg.pool_name} \\`,
    `    disabled=no \\`,
    `    comment="${cfg.comment}"`,
    ``,
  ].join('\n');
}

/**
 * Build user profiles (time-based).
 */
function buildUserProfiles(cfg) {
  const lines = [
    `# ---- User Profiles ----`,
    `/ip hotspot user profile`,
  ];

  cfg.user_profiles.forEach(plan => {
    const spd   = (cfg.profile_speeds || {})[plan] || { up: '5M', down: '10M' };
    const limit = plan === '1H'
      ? `session-timeout=1h`
      : plan === '1D'
        ? `session-timeout=1d`
        : plan === '7D'
          ? `session-timeout=7d`
          : `session-timeout=30d`;

    lines.push(
      `add name="Profile-${plan}" \\`,
      `    rate-limit="${spd.up}/${spd.down}" \\`,
      `    ${limit} \\`,
      `    shared-users=1 \\`,
      `    comment="${plan} plan"`,
    );
  });

  lines.push('');
  return lines.join('\n');
}

/**
 * Build walled garden entries.
 */
function buildWalledGarden(cfg) {
  if (!cfg.walled_garden || cfg.walled_garden.length === 0) return '';

  const lines = [
    `# ---- Walled Garden (no-auth access) ----`,
    `/ip hotspot walled-garden`,
  ];

  cfg.walled_garden.forEach(site => {
    lines.push(`add dst-host=${site} comment="Walled Garden: ${site}"`);
  });

  lines.push('');
  return lines.join('\n');
}

/**
 * Build /ip hotspot walled-garden ip (IP-based bypass).
 */
function buildWalledGardenIP(cfg) {
  return [
    `# ---- Walled Garden IP (DNS servers bypass) ----`,
    `/ip hotspot walled-garden ip`,
    `add dst-address=8.8.8.8 action=accept comment="Google DNS"`,
    `add dst-address=8.8.4.4 action=accept comment="Google DNS Alt"`,
    `add dst-address=1.1.1.1 action=accept comment="Cloudflare DNS"`,
    ``,
  ].join('\n');
}

/**
 * Build example user entries.
 */
function buildExampleUsers(cfg) {
  return [
    `# ---- Example Hotspot Users ----`,
    `/ip hotspot user`,
    `add name=admin password=admin123 profile=Profile-30D comment="Admin User"`,
    `add name=test password=test profile=Profile-1D comment="Test User - 1 Day"`,
    ``,
  ].join('\n');
}

/**
 * Build firewall NAT rule for hotspot.
 */
function buildHotspotNAT(cfg) {
  return [
    `# ---- Hotspot NAT Masquerade ----`,
    `/ip firewall nat`,
    `add action=masquerade chain=srcnat out-interface=!${cfg.hs_interface} \\`,
    `    comment="${cfg.comment} - Masquerade"`,
    ``,
  ].join('\n');
}

/**
 * Main export: Generate complete Hotspot script.
 *
 * @param {Object} config
 * @param {string} config.hs_interface    - Hotspot bridge/interface
 * @param {string} config.hs_ip          - IP/mask for hotspot interface
 * @param {string} config.hs_network     - Hotspot network CIDR
 * @param {string} config.hs_gateway     - Default gateway IP
 * @param {string} config.hs_dns_name    - Captive portal DNS name
 * @param {string} config.pool_name      - DHCP pool name
 * @param {string} config.pool_range     - DHCP pool range
 * @param {string} config.dhcp_lease_time- DHCP lease time
 * @param {string} config.login_method   - 'chap'|'pap'|'mac'|'http-chap'
 * @param {string} config.cookie_lifetime- Cookie lifetime
 * @param {boolean} config.trial_enabled - Enable trial mode
 * @param {string[]} config.user_profiles- Plan codes: ['1H','1D','7D','30D']
 * @param {Object} config.profile_speeds - { '1H': { up:'2M', down:'5M' }, ... }
 * @param {string[]} config.walled_garden- Walled garden domains
 * @returns {string} RouterOS script
 */
function generateHotspot(config) {
  const cfg = validateHotspotConfig(config);

  let script = '';
  script += `#####################################################################\n`;
  script += `# Hotspot Generator - ComitTools Pro\n`;
  script += `# Interface: ${cfg.hs_interface}  |  Network: ${cfg.hs_network}\n`;
  script += `# Login: ${cfg.login_method.toUpperCase()}  |  DNS: ${cfg.hs_dns_name}\n`;
  script += `#####################################################################\n\n`;

  script += buildPool(cfg);
  script += buildDHCP(cfg);
  script += buildHotspotProfile(cfg);
  script += buildHotspotServer(cfg);
  script += buildUserProfiles(cfg);
  script += buildWalledGarden(cfg);
  script += buildWalledGardenIP(cfg);
  script += buildExampleUsers(cfg);
  script += buildHotspotNAT(cfg);

  script += `#####################################################################\n`;
  script += `# DONE - Hotspot setup complete\n`;
  script += `# Login page: http://${cfg.hs_dns_name}\n`;
  script += `#####################################################################\n`;

  return script;
}

// ---- Module Export ----
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { generateHotspot };
} else if (typeof window !== 'undefined') {
  window.generateHotspot = generateHotspot;
}
